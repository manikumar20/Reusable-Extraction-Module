-- Uploaded document identity. Kept in sync with config/migrations/001_create_documents.sql.
CREATE TABLE IF NOT EXISTS documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name TEXT NOT NULL,
  stored_name TEXT NOT NULL,
  mime_type TEXT NOT NULL DEFAULT '',
  document_type TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Pending',
  source TEXT NOT NULL DEFAULT 'AI',
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE documents ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'Pending';
ALTER TABLE documents ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'AI';

CREATE INDEX IF NOT EXISTS documents_uploaded_at
  ON documents (uploaded_at DESC);

CREATE INDEX IF NOT EXISTS documents_document_type
  ON documents (document_type);
