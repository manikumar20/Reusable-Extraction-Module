DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'users'
      AND column_name = 'id'
      AND data_type = 'uuid'
  ) THEN
    CREATE TABLE users_id_migrate (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      name TEXT NOT NULL,
      organization TEXT NOT NULL DEFAULT '',
      role TEXT NOT NULL DEFAULT 'Document reviewer',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    INSERT INTO users_id_migrate (email, password_hash, name, organization, role, created_at, updated_at)
    SELECT email, password_hash, name, organization, role, created_at, updated_at
    FROM users
    ORDER BY created_at ASC, email ASC;

    DROP TABLE users CASCADE;
    ALTER TABLE users_id_migrate RENAME TO users;

    CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique
      ON users (lower(email));
  END IF;
END $$;
